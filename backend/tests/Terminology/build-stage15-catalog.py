"""Build a recognition catalog, separately from approval of standard-code mappings.

Legacy aliases are carried forward with explicit inherited provenance. New recognition
phrases are locally authored. No RxCUI or LOINC identifier is generated by this script.
"""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
source = (ROOT/'Clinical/IndianOntologyResolver.cs').read_text(encoding='utf-8-sig')
entries = []
entries.append(dict(category='NON_MEDICATION',canonical='Pathology or molecular finding',aliases=['blasts','myeloblasts','FLT3','NPM1'],mapping='not_medication',provenance='Apollo clinical semantic exclusion; these findings do not identify medicinal ingredients'))
entries.append(dict(category='INVESTIGATION',canonical='NT-proBNP',aliases=['NT-proBNP','NT proBNP','BNP'],mapping='unresolved',provenance='Apollo recognition lexicon; no specimen or measurement-specific LOINC identifier asserted'))
for category, start, end in [('MEDICATION','DrugMaster =','LabMaster ='),('INVESTIGATION','LabMaster =','private static readonly System.Collections.Concurrent')]:
    segment = source.split(start,1)[1].split(end,1)[0]
    for alias, name in re.findall(r'\["([^"]+)"\]\s*=\s*new\("([^"]+)"', segment):
        entries.append(dict(category=category, canonical=name, aliases=[alias],
                            mapping='legacy_verified_resolver', provenance='Inherited Apollo catalog; standard-code approval remains separately gated'))
meds = ['Cytarabine','Daunorubicin','Levofloxacin','Acyclovir','Midostaurin','Meropenem','Posaconazole',
        'Benzydamine','Apixaban','Rivaroxaban','Dabigatran','Enoxaparin','Heparin','Vancomycin',
        'Ceftriaxone','Cefixime','Doxycycline','Clindamycin','Theophylline','Metoprolol','Carvedilol',
        'Furosemide','Hydrochlorothiazide','Insulin','Insulin glargine','Vincristine','Vinblastine',
        'Cyclophosphamide','Doxorubicin','Etoposide','Paclitaxel','Carboplatin','Oxaliplatin',
        'Capecitabine','Fluorouracil','Rituximab','Trastuzumab','Imatinib','Dasatinib','Hydroxyurea',
        'Voriconazole','Fluconazole','Valacyclovir','Ganciclovir','Oseltamivir','Amitriptyline',
        'Pregabalin','Tramadol','Morphine','Fentanyl','Budesonide','Formoterol','Montelukast','Penicillin']
for name in meds:
    entries.append(dict(category='MEDICATION',canonical=name,aliases=[name],mapping='unresolved',
                        provenance='Apollo recognition lexicon 2026-11-25; no standard identifier asserted'))
invs = {
    'Bone marrow aspirate':['bone marrow aspirate','bone marrow aspiration'],
    'Bone marrow biopsy':['bone marrow biopsy'], 'Blood culture':['blood cultures'],
    'Cytogenetics':['cytogenetics','cytogenetic analysis'], 'Flow cytometry':['flow cytometry'],
    'Molecular mutation testing':['molecular mutation testing','mutation analysis'],
    'Renal function panel':['renal function panel','kidney function panel','renal panel'],
    'Liver function panel':['liver function panel','hepatic function panel','hepatic panel'],
    'Renal/liver function panel':['renal/liver function panel'],
    'Complete blood count':['full blood count','FBC'], 'Hemoglobin':['hemoglobin','haemoglobin'],
    'Platelet count':['platelet count','platelets'], 'Differential count':['differential count','differential leukocyte count'],
    'Peripheral smear':['peripheral smear','peripheral blood smear'], 'Blood glucose':['blood glucose'],
    'Culture and sensitivity':['culture and sensitivity','culture & sensitivity'],
    'Stool antigen testing':['stool antigen testing','stool antigen test'],
    'Echocardiography':['echocardiography'], 'Spirometry':['spirometry'],
    'Histopathology':['histopathology','histopathological examination'],
    'Immunohistochemistry':['immunohistochemistry']
}
for name, aliases in invs.items():
    entries.append(dict(category='INVESTIGATION',canonical=name,aliases=aliases,mapping='unresolved',
                        provenance='Apollo authored clinical phrase catalog 2026-11-25; no LOINC identifier asserted'))
out = ROOT/'Clinical/Terminology/clinical-recognition-v1.json'
out.parent.mkdir(exist_ok=True)
if out.exists(): raise SystemExit('Refusing to overwrite versioned catalog')
out.write_text(json.dumps(dict(version='apollo-clinical-2026-11-25.1',
    license='Apollo-authored recognition phrases and inherited project aliases; standard codes use separately attributed NLM/LOINC snapshots',
    entries=entries),indent=2)+'\n',encoding='utf-8')
print(f'{len(entries)} catalog entries written; no new standard codes assigned')
